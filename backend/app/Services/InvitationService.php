<?php

namespace App\Services;

use App\Models\Event;
use App\Models\Guest;
use App\Models\Invitation;
use Illuminate\Support\Facades\DB;

class InvitationService
{
    /**
     * Normalize an Indonesian WhatsApp number to international digits.
     * 0812... -> 62812... ; +62 812... -> 62812...
     */
    public function normalizePhone(string $phone): string
    {
        $digits = preg_replace('/\D+/', '', $phone);

        if (str_starts_with($digits, '0')) {
            return '62' . substr($digits, 1);
        }

        if (str_starts_with($digits, '620')) {
            return '62' . substr($digits, 3);
        }

        if (str_starts_with($digits, '8')) {
            return '62' . $digits;
        }

        return $digits;
    }

    /**
     * Build (or refresh) the invitation record for a guest.
     * The public token is generated by the Guest model and is never the id.
     */
    public function generateForGuest(Guest $guest): Invitation
    {
        if (empty($guest->unique_token)) {
            $guest->forceFill(['unique_token' => Guest::generateUniqueToken()])->save();
        }

        return DB::transaction(function () use ($guest) {
            $url = $this->invitationUrl($guest);
            $qrPath = '/api/public/invitations/' . $guest->unique_token . '/qr';

            return Invitation::updateOrCreate(
                ['guest_id' => $guest->id],
                [
                    'event_id' => $guest->event_id,
                    'invitation_url' => $url,
                    'qr_code_path' => $qrPath,
                ]
            );
        });
    }

    public function invitationUrl(Guest $guest): string
    {
        $guest->loadMissing('event');

        $path = $guest->event?->event_type === 'santri'
            ? '/santri/undangan/'
            : '/undangan/';

        return config('whatsapp.frontend_url') . $path . $guest->unique_token;
    }

    public function buildMessage(Invitation $invitation, ?string $custom = null): string
    {
        $invitation->loadMissing(['guest', 'event']);

        /** @var Guest $guest */
        $guest = $invitation->guest;
        /** @var Event $event */
        $event = $invitation->event;

        $template = $custom ?: config('whatsapp.message_template');

        return str_replace(
            [
                '{nama_tamu}',
                '{nama_acara}',
                '{tanggal_acara}',
                '{waktu_acara}',
                '{lokasi_acara}',
                '{link_undangan}',
            ],
            [
                $guest->whatsappRecipientName(),
                $event->name,
                $this->formatDate($event->event_date),
                $this->formatTime($event->event_time),
                $event->location,
                $invitation->invitation_url,
            ],
            $template
        );
    }

    public function formatDate($date): string
    {
        if (!$date) {
            return '-';
        }

        $months = [
            1 => 'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
            'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember',
        ];

        $timestamp = strtotime((string) $date);

        return date('j', $timestamp) . ' ' . $months[(int) date('n', $timestamp)] . ' ' . date('Y', $timestamp);
    }

    public function formatTime(?string $time): string
    {
        if (!$time) {
            return '-';
        }

        return substr($time, 0, 5) . ' WIB';
    }

    public function clickToChatUrl(string $phone, string $message): string
    {
        return 'https://wa.me/' . $this->normalizePhone($phone) . '?text=' . rawurlencode($message);
    }
}
